"""Copy SoH's location-registering functions (Rando::StaticData::Register*Locations / *Location) out of the
randomizer's Shuffle*.cpp files, unchanged, into gen/locations_gen.cpp, without the game code around them.
usage: python -I extract_locations.py <randomizer dir> <out.cpp>"""
import re, sys, glob, os
src_dir, out = sys.argv[1:3]
funcs, names, consts = [], [], []
for p in sorted(glob.glob(os.path.join(src_dir, 'Shuffle*.cpp'))):
    s = open(p, encoding='utf-8').read()
    for m in re.finditer(r'void Rando::StaticData::(Register\w+Locations?)\(\)\s*\{', s):
        i = m.end(); depth = 1
        while depth:
            depth += {'{': 1, '}': -1}.get(s[i], 0); i += 1
        funcs.append(f'// from {os.path.basename(p)}\n' + s[m.start():i]); names.append(m.group(1))
hdr = ('// GENERATED by tools/extract_locations.py from SoH sources: location tables only.\n'
       '#include "soh/Enhancements/randomizer/static_data.h"\n#include "soh/Enhancements/randomizer/location.h"\n'
       '#include "soh/Enhancements/randomizer/SeedContext.h"\n#include "soh/Enhancements/randomizer/fishsanity.h"\n'
       '#include "z64.h"\n#include "variables.h"\n#include "macros.h"\n'
       '#include "soh/Enhancements/custom-message/CustomMessageTypes.h"\n')
body = '\n\n'.join(funcs)
call = ('void Remake_RegisterAllLocations() {\n'
        '    Rando::StaticData::RegisterFishLocations(); // fishsanity.cpp, compiled whole\n') + ''.join(f'    Rando::StaticData::{n}();\n' for n in names) + '}\n'
open(out, 'w', encoding='utf-8').write(hdr + body + '\n\n' + call)
print(len(names), names)
